-- ----------------------------------------------------------------------------
-- Schema
-- ----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS payments;

-- ----------------------------------------------------------------------------
-- Domain type: status enum (ADR-002)
-- Canonical set — NOTE: 'G','P','E','C','D','X','R' (legacy chars) are NOT
-- stored here. The ConciliacaoService and FolhaService write the enum name.
-- De-para table for legacy migration: db/migration/notes/status-depara.md
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'status_pagamento'
                   AND typnamespace = (SELECT oid FROM pg_namespace WHERE nspname = 'payments')) THEN
        CREATE TYPE payments.status_pagamento AS ENUM (
            'GERADO',    -- folha generated by FolhaService (legacy 'G')
            'EMITIDO',   -- remessa sent to bank (legacy DDM 'E')
            'PAGO',      -- bank confirmed credit, ret '00' (legacy 'P' in BATCHCON)
            'DEVOLVIDO', -- bank returned, ret '01'         (legacy 'D')
            'ERRO',      -- bank error, ret '02'            (legacy 'E' in BATCHCON)
            'CANCELADO', -- cancelled (legacy 'C' — orphan, source TBD per OQ-01)
            'ESTORNADO'  -- reversed after payment          (legacy 'E' in BATCHREL)
        );
    END IF;
END $$;

-- ----------------------------------------------------------------------------
-- Sequence for NUM-PAGAMENTO (replaces Adabas auto-increment mechanism)
-- Allocation size 50 matches @SequenceGenerator allocationSize in entity.
-- ----------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS payments.pagamento_num_seq
    START WITH 1
    INCREMENT BY 50
    NO MAXVALUE
    CACHE 50;

-- ----------------------------------------------------------------------------
-- Main table: pagamento
-- Range-partitioned by ano_mes_ref (NUMERIC(6) = AAAAMM).
-- ADR-003: partition enables efficient archival of historic months (~180M rows).
-- ============================================================================
-- NOTE: PostgreSQL range partitioning requires creating child partitions
-- separately (see partition management section below).
-- ----------------------------------------------------------------------------
CREATE TABLE payments.pagamento (
    -- ── Identity (DDM: AA-AF) ──────────────────────────────────────────────
    num_pagamento       BIGINT          NOT NULL DEFAULT nextval('payments.pagamento_num_seq'),
    num_cpf             CHAR(11)        NOT NULL,   -- DDM: AB (DE)
    num_inscricao       BIGINT,                     -- DDM: AC cross-ref to BENEFICIARIO
    cod_programa        CHAR(4)         NOT NULL,   -- DDM: AD (DE)
    ano_mes_ref         NUMERIC(6)      NOT NULL,   -- DDM: AE (DE) partition key (AAAAMM)
    num_ciclo           INTEGER,                    -- DDM: AF

    -- ── Tipo pagamento (designed addition, not in DDM) ────────────────────
    -- FIXME: confirm 'T' (TERCEIRO) semantics — no legacy program writes it
    tipo_pgto           CHAR(1) CHECK (tipo_pgto IN ('N','D','T')),

    -- ── Monetary values (DDM: BA-BC) ──────────────────────────────────────
    -- All NUMERIC(9,2) per DDM. Truncated, never rounded (REQ-021).
    vlr_bruto           NUMERIC(9,2)    NOT NULL,
    vlr_liquido         NUMERIC(9,2)    NOT NULL CHECK (vlr_liquido >= 0),  -- REQ-028
    vlr_desconto_total  NUMERIC(9,2)    NOT NULL DEFAULT 0,

    -- Abono natalino (designed addition — 13th salary bonus, REQ-022/023)
    vlr_abono           NUMERIC(9,2),

    -- ── Status (DDM: DA) ──────────────────────────────────────────────────
    sit_pagamento       payments.status_pagamento NOT NULL,  -- ADR-002

    -- ── Status timestamps (DDM: DB-DG) ────────────────────────────────────
    dt_geracao          DATE,           -- DDM: DB (DE, YYYYMMDD)
    hr_geracao          TIME,           -- DDM: DC
    dt_emissao          DATE,           -- DDM: DD
    dt_confirmacao      DATE,           -- DDM: DE
    dt_cancelamento     DATE,           -- DDM: DF
    mot_cancelamento    CHAR(3),        -- DDM: DG

    -- ── Monetary correction (designed addition) ───────────────────────────
    ind_corrigido       BOOLEAN         NOT NULL DEFAULT FALSE,  -- REQ-034
    vlr_correcao        NUMERIC(9,2),
    dt_correcao         DATE,

    -- ── Bank routing (DDM: EA-EE, MYS-010 resolved) ───────────────────────
    cod_banco           CHAR(3),        -- DDM: EA (FEBRABAN)
    cod_agencia         VARCHAR(6),     -- DDM: EB
    num_conta           VARCHAR(13),    -- DDM: EC
    tipo_conta          CHAR(1)  CHECK (tipo_conta IN ('C','P')),  -- DDM: ED
    cod_operacao        CHAR(3),        -- DDM: EE (Caixa Econômica, nullable)

    -- ── SIAFI integration (DDM: FA-FE, added 2002) ────────────────────────
    num_ob_siafi        VARCHAR(12),    -- DDM: FA (Ordem Bancária SIAFI)
    num_ne_siafi        VARCHAR(12),    -- DDM: FB (Nota de Empenho SIAFI)
    cod_ug_emitente     VARCHAR(6),     -- DDM: FC
    cod_gestao          VARCHAR(5),     -- DDM: FD
    sit_integ_siafi     CHAR(1) CHECK (sit_integ_siafi IN ('I','P','E')),  -- DDM: FE

    -- ── CNAB reconciliation (DDM: GA-GE) ──────────────────────────────────
    dt_conciliacao      DATE,           -- DDM: GA
    sit_conciliacao     CHAR(1) CHECK (sit_conciliacao IN ('C','D','P','N')),  -- DDM: GB
    vlr_conciliado      NUMERIC(9,2),   -- DDM: GC
    cod_retorno_banco   CHAR(2),        -- DDM: GD
    des_retorno_banco   VARCHAR(40),    -- DDM: GE

    -- ── File hashes (DDM: HA-HB, added 2015) ──────────────────────────────
    hash_arq_remessa    CHAR(64),       -- DDM: HA SHA-256
    hash_arq_retorno    CHAR(64),       -- DDM: HB SHA-256

    -- ── Audit control (DDM: IA-IF) ────────────────────────────────────────
    dt_inclusao         DATE            NOT NULL DEFAULT CURRENT_DATE,  -- DDM: IA
    hr_inclusao         TIME            NOT NULL DEFAULT CURRENT_TIME,  -- DDM: IB
    usr_inclusao        VARCHAR(8)      NOT NULL DEFAULT 'SYSTEM',      -- DDM: IC
    dt_ult_alteracao    DATE,           -- DDM: ID
    hr_ult_alteracao    TIME,           -- DDM: IE
    usr_ult_alteracao   VARCHAR(8),     -- DDM: IF

    PRIMARY KEY (num_pagamento, ano_mes_ref)  -- compound PK required for range partition
) PARTITION BY RANGE (ano_mes_ref);

-- Unique constraint enforcing REQ-030 (one payment per beneficiary per month)
CREATE UNIQUE INDEX uq_pagamento_cpf_competencia
    ON payments.pagamento (num_cpf, ano_mes_ref);

-- Super-descriptor S1: AB + AE — CPF + COMPETENCIA
CREATE INDEX idx_pagamento_s1_cpf_competencia
    ON payments.pagamento (num_cpf, ano_mes_ref);

-- Super-descriptor S2: AD + AE + DA — PROGRAMA + COMPET + SITUACAO
CREATE INDEX idx_pagamento_s2_prog_comp_status
    ON payments.pagamento (cod_programa, ano_mes_ref, sit_pagamento);

-- Super-descriptor S3: AF + DA — CICLO + SITUACAO
CREATE INDEX idx_pagamento_s3_ciclo_status
    ON payments.pagamento (num_ciclo, sit_pagamento);

-- DE field: DT-GERACAO
CREATE INDEX idx_pagamento_dt_geracao ON payments.pagamento (dt_geracao);

