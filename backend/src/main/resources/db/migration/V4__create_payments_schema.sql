-- ----------------------------------------------------------------------------
-- Child table: pagamento_desconto
-- GRP-DESCONTO (CA, PE, max 8) — ADR-003: @ElementCollection per Desconto.
-- Inherits partition key from parent via num_pagamento + ano_mes_ref (included
-- in order to co-locate desconto rows with their parent partition).
-- ----------------------------------------------------------------------------
CREATE TABLE payments.pagamento_desconto (
    num_pagamento   BIGINT          NOT NULL,
    ano_mes_ref     NUMERIC(6)      NOT NULL,   -- for partition co-location
    ocorrencia_idx  SMALLINT        NOT NULL,   -- PE occurrence order (0-based)

    -- DDM: CB TIPO-DESCONTO A 3 — REQ-025/026/027
    tipo_desconto   VARCHAR(3)      NOT NULL,

    -- DDM: CC VLR-DESCONTO N 7.2
    vlr_desconto    NUMERIC(9,2)    NOT NULL,

    -- DDM: CD PCT-DESCONTO N 3.2
    pct_desconto    NUMERIC(5,2),

    -- DDM: CE NUM-PROCESSO A 20 (required when tipo_desconto = 'JD', REQ-027)
    num_processo    VARCHAR(20),

    -- DDM: CF DT-INICIO-DSCT N 8 (YYYYMMDD → DATE)
    dt_inicio_dsct  DATE,

    -- DDM: CG DT-FIM-DSCT N 8 (YYYYMMDD → DATE; NULL = indefinido)
    dt_fim_dsct     DATE,

    PRIMARY KEY (num_pagamento, ano_mes_ref, ocorrencia_idx),

    FOREIGN KEY (num_pagamento, ano_mes_ref)
        REFERENCES payments.pagamento (num_pagamento, ano_mes_ref)
        ON DELETE CASCADE
);

-- Index required by REQ-025/026/027 (sum/filter by discount type)
CREATE INDEX idx_pgto_dsct_tipo       ON payments.pagamento_desconto (tipo_desconto);
CREATE INDEX idx_pgto_dsct_pagamento  ON payments.pagamento_desconto (num_pagamento, ano_mes_ref);

-- Check: judicial discount must have a process number (REQ-027)
ALTER TABLE payments.pagamento_desconto
    ADD CONSTRAINT chk_judicial_numprocesso
    CHECK (tipo_desconto <> 'JD' OR num_processo IS NOT NULL);

